const I18N = {
  lang: (() => {
    const l = (navigator.language || 'en').slice(0, 2);
    return DVT_STRINGS[l] ? l : 'en';
  })(),
  t(key) {
    return (DVT_STRINGS[this.lang] && DVT_STRINGS[this.lang][key]) ||
      DVT_STRINGS.en[key] || key;
  },
  async init() {
    try {
      const s = await chrome.storage.local.get('dvtSettings');
      const l = s.dvtSettings && s.dvtSettings.setUiLang;
      if (l && DVT_STRINGS[l]) this.lang = l;
    } catch (e) { /* storage nav pieejams — paliekam pie pārlūka valodas */ }
    this.apply();
  },
  setLang(l) {
    if (DVT_STRINGS[l]) this.lang = l;
    this.apply();
  },
  apply() {
    document.querySelectorAll('[data-i18n]').forEach(
      (el) => (el.textContent = this.t(el.dataset.i18n)));
    document.querySelectorAll('[data-i18n-ph]').forEach(
      (el) => (el.placeholder = this.t(el.dataset.i18nPh)));
  },
};

const t = (k) => I18N.t(k);
